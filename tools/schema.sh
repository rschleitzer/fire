#!/bin/bash
# tools/schema.sh -- the scripts the generator wrote for each database
# (server/<name>/sql/*.sql: the schema, and the two that make and drop the
# search indexes -- upstream's own, by its own DSSSL) as records of the
# model's text: server/<name>/Schema.scaly. tools/generate.sh runs it.
#   tools/schema.sh <name of the program: fire>
set -eu
cd "$(dirname "$0")/.."
name=${1:-fire}
to="server/$name/Schema.scaly"

{
  echo "; GENERATED by tools/schema.sh from server/$name/sql. Do not edit."
  echo ";"
  echo "; Records of the model's text (Model.scaly): for each database the script"
  echo "; that creates the schema, and the two that make and drop the indexes."
  echo
  echo "procedure schema_write(mutable out: ref[Array[u8]])"
  echo "{"
  for f in "server/$name"/sql/*.sql; do
    [ -s "$f" ] || { echo "schema: $f is empty" >&2; exit 1; }
    key=$(basename "$f" .sql)
    printf '    record(out, "@@=:%s\\n' "$key"
    awk '{ gsub(/\\/, "\\\\"); gsub(/"/, "\\\""); gsub(/`/, "\\`"); printf "%s\\n", $0 }' "$f"
    printf '\\n")\n'
  done
  echo "}"
} > "$to"
