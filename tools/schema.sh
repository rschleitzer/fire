#!/bin/bash
# tools/schema.sh -- the schema the Scaly server creates is upstream's, to the
# byte: cut the scripts of each provider out of the generated C# (the
# InitialSchema, and the two that make and drop the search indexes) and
# write them as records of the model's text into server/<name>/Schema.scaly
# (generated, not in git). tools/generate.sh runs it.
#   tools/schema.sh <name of the program: fire>
set -eu
cd "$(dirname "$0")/.."
name=${1:-fire}
to="server/$name/Schema.scaly"

# a script of a provider (a raw string property) as one record
script() {  # <property> <key> <file>
  printf '    record(out, "@@=:%s\\n' "$2"
  awk -v start="public string $1 => \"\"\"" '
    index($0, start) { inside = 1; next }
    inside && /^""";/ { exit }
    inside {
      gsub(/\\/, "\\\\"); gsub(/"/, "\\\""); gsub(/`/, "\\`")
      printf "%s\\n", $0
    }' "$3"
  printf '\\n")\n'
}

one() {  # <provider directory of upstream> <its name in the keys>
  local from="upstream/server/Repositories/$1/DatabaseProvider.cs"
  [ -f "$from" ] || { echo "schema: no $from -- run upstream/fire.sh first" >&2; exit 1; }
  script InitialSchema "$2.schema" "$from"
  script CreateIndexesSql "$2.indexes.create" "$from"
  script DropIndexesSql "$2.indexes.drop" "$from"
}

mkdir -p "server/$name"
{
  echo "; GENERATED by tools/schema.sh from upstream's providers. Do not edit."
  echo ";"
  echo "; Records of the model's text (Model.scaly): for each database the script"
  echo "; that creates the schema, and the two that make and drop the indexes."
  echo
  echo "procedure schema_write(mutable out: ref[Array[u8]])"
  echo "{"
  one postgresql postgresql
  echo "}"
} > "$to"
[ "$(wc -c < "$to")" -gt 1000 ] || { echo "schema: no InitialSchema found" >&2; exit 1; }
